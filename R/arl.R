#' Average run length of an AEWMA chart by simulation
#'
#' Estimates the average run length (ARL), its standard deviation (SDRL) and
#' standard error for one of the nine charts, for subgroups drawn from a
#' normal distribution with variance `shift` (in-control standard deviation 1,
#' so `shift = 1` gives the in-control ARL0).
#'
#' The result depends only on `seed`, `n_streams` and `nsim`. The simulation
#' work is split into `n_streams` independent random number streams; with the
#' default `n_streams = 3` the numbers equal those used to calibrate the
#' control limits. `n_cores` only sets how many worker processes run the
#' streams and never changes the result. The random number generator state of
#' the calling session is left unchanged.
#'
#' @param method One of `"nn"`, `"qrnn"`, `"mcqrnn"`, `"svr"`, `"svqr"`,
#'   `"rsvqr"`, `"dt"`, `"gb"`, `"dqr"`.
#' @param h_value Control limit.
#' @param shift Variance multiplier of the simulated process (1 = in control).
#' @param subgroup_size Subgroup size; only 5 is supported.
#' @param nsim Number of simulated charts (at least 2).
#' @param max_rl Maximum run length; longer runs are censored.
#' @param seed Random seed.
#' @param n_cores Number of worker processes (1 = no cluster). At most 2 are
#'   used while `R CMD check` runs.
#' @param block Number of subgroups generated at a time (speed only; ignored
#'   for `"dqr"`). It does not change the results.
#' @param n_streams Number of independent random number streams (see
#'   Details). `1` uses a single Mersenne-Twister stream.
#' @return A named numeric vector with `ARL`, `SDRL`, `ARL_SE` and
#'   `Censor_Rate` (share of runs that reached `max_rl`).
#' @examples
#' calculate_arl("nn", h_value = 0.846, nsim = 30, seed = 1, n_streams = 1)
#' @export
calculate_arl <- function(method, h_value, shift = 1, subgroup_size = 5,
                          nsim = 500, max_rl = 10000, seed = 42, n_cores = 1L,
                          block = 500, n_streams = 3L) {
  method <- .match_method(method, .ALL_METHODS, "calculate_arl()")
  .check_subgroup_size(subgroup_size)
  .check_pos(h_value, "h_value")
  .check_pos(shift, "shift")
  .check_seed(seed)
  .arl(method, as.numeric(h_value), shift, nsim, max_rl, seed, n_cores,
       n_streams, block)
}

# Case-insensitive exact match with a message that names the function.
.match_method <- function(method, choices, fun) {
  if (!is.character(method) || length(method) != 1L ||
        !(tolower(method) %in% choices)) {
    stop("`method` must be one of ", paste(dQuote(choices, FALSE), collapse = ", "),
         " for ", fun, ".", call. = FALSE)
  }
  tolower(method)
}

.check_subgroup_size <- function(subgroup_size) {
  if (!is.numeric(subgroup_size) || !isTRUE(subgroup_size == 5)) {
    stop(
      "The transformation constants, models and control limits are ",
      "calibrated for subgroup_size = 5.",
      call. = FALSE
    )
  }
  invisible(TRUE)
}

.arl <- function(method, h_value, shift, nsim, max_rl, seed, n_cores,
                 n_streams, block = 500) {
  lagged <- identical(method, "dqr")
  predict_theta <- if (lagged) .theta_fun_dqr() else .theta_fun(method)

  rl <- .simulate_run_lengths(
    predict_theta = predict_theta, h_value = h_value, shift = shift,
    subgroup_size = 5, nsim = nsim, max_rl = max_rl, seed = seed,
    n_streams = n_streams, n_cores = n_cores, block = block, lagged = lagged
  )

  if (length(rl) == 0) {
    stop("No run-length results were generated by the Monte Carlo simulation.",
         call. = FALSE)
  }

  arl_value <- mean(rl)
  sdrl_value <- stats::sd(rl)
  censor_rate <- mean(rl >= max_rl)

  if (censor_rate > 0.01) {
    warning("More than 1% of simulations reached max_rl. ",
            "Increase max_rl before interpreting this ARL.", call. = FALSE)
  }

  c(ARL = arl_value, SDRL = sdrl_value,
    ARL_SE = sdrl_value / sqrt(length(rl)), Censor_Rate = censor_rate)
}
